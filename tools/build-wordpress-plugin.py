"""Builds the relay core of the VPN Server WordPress plugin from phpvpn.php.

phpvpn.php stays the single source of the wire protocol. Everything after `namespace PhpVpn;`
is copied into server/wordpress/version7/vpn-server/includes/relay-core.php, except the
regions between `// @wp-skip-begin` and `// @wp-skip-end`, which belong to the standalone
file only (configuration header, process wide runtime settings, status page and autorun).

    python tools/build-wordpress-plugin.py            regenerate relay-core.php
    python tools/build-wordpress-plugin.py --check    fail when relay-core.php or a version is stale
    python tools/build-wordpress-plugin.py --zip DIR  also write DIR/vpn-server-X.Y.Z.zip
"""
import argparse
import pathlib
import re
import sys
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'phpvpn.php'
PLUGIN = ROOT / 'server' / 'wordpress' / 'version7' / 'vpn-server'
CORE = PLUGIN / 'includes' / 'relay-core.php'
SLUG = 'vpn-server'

SKIP_BEGIN = '// @wp-skip-begin'
SKIP_END = '// @wp-skip-end'

HEADER = '''<?php
/**
 * PHP VPN relay core of the VPN Server plugin, version {version}.
 *
 * GENERATED by tools/build-wordpress-plugin.py from phpvpn.php of the PHP VPN project.
 * Do not edit this file. Change phpvpn.php and run the build again.
 *
 * MIT License, Copyright (c) www.pilandrome.com
 *
 * @package VpnServer
 */

declare(strict_types=1);

namespace PhpVpn;

if ( ! defined( 'ABSPATH' ) ) {{
\texit;
}}
'''


def read_text(path: pathlib.Path) -> str:
    return path.read_text(encoding='utf-8').replace('\r\n', '\n')


def server_version(source: str) -> str:
    match = re.search(r"^const SERVER_VERSION = '(\d+\.\d+\.\d+)';$", source, re.MULTILINE)
    if not match:
        raise SystemExit('phpvpn.php: SERVER_VERSION not found')
    return match.group(1)


def strip_skipped(lines: list[str]) -> list[str]:
    kept: list[str] = []
    skipping = False
    for number, line in enumerate(lines, start=1):
        marker = line.strip()
        if marker.startswith(SKIP_BEGIN):
            if skipping:
                raise SystemExit(f'phpvpn.php: nested {SKIP_BEGIN} on line {number}')
            skipping = True
            continue
        if marker.startswith(SKIP_END):
            if not skipping:
                raise SystemExit(f'phpvpn.php: {SKIP_END} without a begin on line {number}')
            skipping = False
            continue
        if not skipping:
            kept.append(line)
    if skipping:
        raise SystemExit(f'phpvpn.php: unterminated {SKIP_BEGIN}')
    return kept


def build_core(source: str) -> str:
    lines = source.split('\n')
    try:
        start = lines.index('namespace PhpVpn;') + 1
    except ValueError:
        raise SystemExit('phpvpn.php: `namespace PhpVpn;` not found') from None
    body = '\n'.join(strip_skipped(lines[start:]))
    banner = '// 1. Configuration header. This is the only part an administrator edits.'
    if banner not in body:
        raise SystemExit('phpvpn.php: the section 1 banner changed, update build-wordpress-plugin.py')
    # The plugin settings hold the secret, keys and storage, the protocol constants stay fixed.
    body = body.replace(banner, '// 1. Protocol constants. Secret, access keys and storage come from the plugin settings.')
    # Collapse the blank lines left behind by removed regions.
    body = re.sub(r'\n{3,}', '\n\n', body).strip('\n')
    return HEADER.format(version=server_version(source)) + '\n' + body + '\n'


def version_problems(version: str) -> list[str]:
    problems = []
    checks = [
        (PLUGIN / f'{SLUG}.php', r'^ \* Version:\s+(\d+\.\d+\.\d+)$'),
        (PLUGIN / f'{SLUG}.php', r"^const VERSION = '(\d+\.\d+\.\d+)';$"),
        (PLUGIN / 'readme.txt', r'^Stable tag: (\d+\.\d+\.\d+)$'),
    ]
    for path, pattern in checks:
        found = re.findall(pattern, read_text(path), re.MULTILINE)
        if found != [version]:
            problems.append(f'{path.relative_to(ROOT)}: {found or "no"} version instead of {version}')
    return problems


def write_zip(directory: pathlib.Path, version: str) -> pathlib.Path:
    directory.mkdir(parents=True, exist_ok=True)
    target = directory / f'{SLUG}-{version}.zip'
    files = sorted(path for path in PLUGIN.rglob('*') if path.is_file())
    with zipfile.ZipFile(target, 'w', zipfile.ZIP_DEFLATED) as archive:
        for path in files:
            archive.write(path, f'{SLUG}/{path.relative_to(PLUGIN).as_posix()}')
    return target


def main() -> int:
    arguments = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    arguments.add_argument('--check', action='store_true', help='verify instead of writing')
    arguments.add_argument('--zip', type=pathlib.Path, help='directory for the installable plugin ZIP')
    options = arguments.parse_args()

    source = read_text(SOURCE)
    version = server_version(source)
    core = build_core(source)

    if options.check:
        problems = version_problems(version)
        if not CORE.is_file() or read_text(CORE) != core:
            problems.insert(0, f'{CORE.relative_to(ROOT)} is stale, run tools/build-wordpress-plugin.py')
        for problem in problems:
            print(problem, file=sys.stderr)
        if problems:
            return 1
        print(f'VPN Server plugin {version} is up to date.')
        return 0

    CORE.parent.mkdir(parents=True, exist_ok=True)
    with CORE.open('w', encoding='utf-8', newline='\n') as handle:
        handle.write(core)
    print(f'Wrote {CORE.relative_to(ROOT)} from phpvpn.php {version}.')
    problems = version_problems(version)
    for problem in problems:
        print(problem, file=sys.stderr)
    if options.zip:
        if problems:
            return 1
        print(f'Wrote {write_zip(options.zip, version)}.')
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
