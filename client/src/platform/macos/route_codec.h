// Pure PF_ROUTE message encoding and decoding (plan-macos-v001 step 5).
//
// The codec is free of sockets and privileges, so the unit tests can feed it
// synthetic kernel answers; route_socket.h only moves the bytes. A routing
// message is an rt_msghdr followed by the socket addresses named in rtm_addrs,
// packed in RTA_* bit order, each padded to a multiple of sizeof(uint32_t); a
// socket address with sa_len 0 still occupies four bytes. The kernel sends
// netmasks in the trimmed radix form: sin_len may end inside sin_addr (0 for
// the default route, 5 to 8 for the usual prefixes) and the family byte of a
// mask is not reliable, so a mask is read from the sin_addr offset up to its
// length and the missing bytes are zero.
#pragma once

#include <cstddef>
#include <cstdint>
#include <optional>
#include <span>
#include <vector>

#include "core/base/result.h"
#include "core/protocol/ipv4.h"

namespace phpvpn::routing {

using Bytes = std::vector<std::uint8_t>;

// Route flags of <net/route.h> by value. They are the xnu ABI; route_codec.cpp
// checks them against the SDK wherever the SDK defines the macro.
inline constexpr int kFlagLlinfo = 0x400;         // RTF_LLINFO, link-layer (ARP) entry
inline constexpr int kFlagWasCloned = 0x20000;    // RTF_WASCLONED, generated by cloning
inline constexpr int kFlagLocal = 0x200000;       // RTF_LOCAL, a local address
inline constexpr int kFlagBroadcast = 0x400000;   // RTF_BROADCAST
inline constexpr int kFlagMulticast = 0x800000;   // RTF_MULTICAST
inline constexpr int kFlagIfScope = 0x1000000;    // RTF_IFSCOPE, interface scoped duplicate

// One request to the routing socket.
struct RouteRequest {
    int type = 0;      // RTM_ADD, RTM_DELETE or RTM_GET
    int flags = 0;     // RTF_*
    int sequence = 0;  // rtm_seq, filled in by RouteSocket::request
    int pid = 0;       // rtm_pid, filled in by RouteSocket::request
    Ipv4Address destination;
    // RTA_NETMASK as a full sockaddr_in. Absent: a longest match RTM_GET.
    std::optional<Ipv4Address> netmask;
    // RTA_GATEWAY as sockaddr_in, a next hop (used with RTF_GATEWAY) ...
    std::optional<Ipv4Address> gateway;
    // ... or, when `gateway` is absent and this is positive, as a sockaddr_dl
    // whose sdl_index names the interface of an interface route.
    int gatewayInterfaceIndex = 0;
    // RTA_IFP as a sockaddr_dl with this sdl_index. 0 is the empty query form
    // that makes RTM_GET report the interface, a positive index pins the
    // interface of an added route.
    std::optional<int> interfaceIndex;
};

// One decoded rt_msghdr message with its AF_INET and AF_LINK addresses. The
// addresses of other families are skipped.
struct RouteMessage {
    int length = 0;   // rtm_msglen
    int version = 0;  // rtm_version
    int type = 0;     // rtm_type
    int index = 0;    // rtm_index, the interface of the route
    int flags = 0;    // rtm_flags
    int addrs = 0;    // rtm_addrs
    int pid = 0;      // rtm_pid
    int sequence = 0; // rtm_seq
    int errnoValue = 0;  // rtm_errno, or the errno of a refused write
    int destinationFamily = 0;  // sa_family of RTA_DST, 0 when absent
    std::optional<Ipv4Address> destination;
    std::optional<Ipv4Address> gateway;           // RTA_GATEWAY of AF_INET
    std::optional<int> gatewayLinkIndex;          // RTA_GATEWAY of AF_LINK, its sdl_index
    std::optional<Ipv4Address> netmask;           // RTA_NETMASK, trimmed form expanded
    std::optional<int> interfaceIndex;            // RTA_IFP, its sdl_index
    std::optional<Ipv4Address> interfaceAddress;  // RTA_IFA of AF_INET
};

// Contiguous mask of `prefixLength` leading ones; the length is clamped to 0..32.
Ipv4Address netmaskForPrefix(int prefixLength) noexcept;

// Prefix length of a contiguous mask; any other mask is an error.
Result<int> prefixLengthOfNetmask(Ipv4Address netmask);

// Mask carried by one socket address in any of the forms the kernel uses: the
// bytes from the sin_addr offset up to sa_len (bounded by the span), missing
// bytes zero, the family byte ignored. An empty span or sa_len 0 is 0.0.0.0.
Ipv4Address netmaskFromSockaddr(std::span<const std::uint8_t> address) noexcept;

// Prefix length of a decoded route: a host route (RTF_HOST or no netmask) is
// /32, otherwise the length of its contiguous netmask.
Result<int> routePrefixLength(const RouteMessage& message);

// Interface of a decoded route: rtm_index, else the sdl_index of RTA_IFP, else 0.
int routeInterfaceIndex(const RouteMessage& message) noexcept;

// rt_msghdr (RTM_VERSION) followed by RTA_DST, RTA_GATEWAY, RTA_NETMASK and
// RTA_IFP as requested, every socket address with its full length.
Bytes encode(const RouteRequest& request);

// True when `message` is an rt_msghdr of RTM_VERSION with exactly this type,
// sequence number and process id. Never reads past the buffer.
bool isReplyTo(std::span<const std::uint8_t> message, int type, int sequence, int pid) noexcept;

// One message of the rt_msghdr types (RTM_ADD to RTM_RESOLVE). A short buffer,
// a length outside the buffer, another version or type, or an address running
// past rtm_msglen is malformed.
Result<RouteMessage> decode(std::span<const std::uint8_t> message);

// Every RTM_GET message of a sysctl NET_RT_DUMP buffer. Records of another
// version or type are skipped by their rtm_msglen; a record length below the
// common header or past the end of the buffer is malformed.
Result<std::vector<RouteMessage>> decodeDump(std::span<const std::uint8_t> buffer);

}  // namespace phpvpn::routing
